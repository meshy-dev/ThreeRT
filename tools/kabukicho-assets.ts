// Generated assets of the Kabukichō UE port: the UE 5.8 session's sign / screen / interior textures and masks
// (its Pillow generators, vendored in tools/kabukicho/, byte-identical output) and the sign manifest the game imports.
//   node tools/kabukicho-assets.ts      -> assets/kabukicho/{textures,masks}, games/kabukicho/ue-manifest.ts
// Needs python3; Pillow + numpy are installed into out/.venv-kb on first use. Poly Haven sets: fetch-polyhaven --set kabukicho-ue.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const venv = join(root, "out/.venv-kb");
const py = join(venv, "bin/python");
if (!existsSync(py)) {
  execFileSync("python3", ["-m", "venv", venv], { stdio: "inherit" });
  execFileSync(py, ["-m", "pip", "install", "--quiet", "pillow", "numpy"], { stdio: "inherit" });
}
const textures = join(root, "assets/kabukicho/textures");
const masks = join(root, "assets/kabukicho/masks");
// -I: isolated mode (no script-directory / cwd imports)
execFileSync(py, ["-I", join(root, "tools/kabukicho/gen_signs.py"), textures], { stdio: "inherit" });
execFileSync(py, ["-I", join(root, "tools/kabukicho/gen_masks.py"), masks], { stdio: "inherit" });

// Python json.dumps formatting (", " / ": "), so entries read exactly like the session's manifest.json.
const dumps = (v: unknown): string =>
  Array.isArray(v) ? `[${v.map(dumps).join(", ")}]`
  : v && typeof v === "object" ? `{${Object.entries(v).map(([k, x]) => `${JSON.stringify(k)}: ${dumps(x)}`).join(", ")}}`
  : JSON.stringify(v);
const manifest = JSON.parse(readFileSync(join(textures, "manifest.json"), "utf8")) as unknown[];
const out = [
  "// Sign / screen / interior texture set of the UE 5.8 Kabukichō session (tools/kabukicho/gen_signs.py, seed 20261104):",
  "// name, kind and average glow colour (colours each sign's light). Textures: assets/kabukicho/textures/<name>.png.",
  "// Generated by tools/kabukicho-assets.ts; do not edit.",
  "export interface SignEntry { name: string; kind: string; size: [number, number]; glow: [number, number, number]; interior?: string }",
  "export const MANIFEST: SignEntry[] = [",
  ...manifest.map((e) => `  ${dumps(e)},`),
  "];",
  "",
].join("\n");
writeFileSync(join(root, "games/kabukicho/ue-manifest.ts"), out);
console.log(`kabukicho assets: ${manifest.length} sign textures, masks -> assets/kabukicho; games/kabukicho/ue-manifest.ts`);
