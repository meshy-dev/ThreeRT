//! The engine's scene: objects, geometry, materials, textures, lights, environment, created and edited by scene code
//! through the engine API (the binding in packages/scene/src/engine.ts, installed into the embedded JS runtime by
//! script.rs). There is no scene document in between: the binding calls these operations directly.
//!
//! Every operation records what it changed. Parameter changes (node power, light colour / intensity, material
//! parameters, wetness / rain / fog, the camera) are applied by `LiveCore::commit` to the GPU tables in place;
//! anything else (objects added / removed / moved / hidden, geometry, textures, material functions, sky) rebuilds the
//! GPU scene from the world.

use crate::desc;
use anyhow::{anyhow, Result};
use glam::{Mat4, Quat, Vec3};
use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::sync::Arc;

/// Triangle mesh data as the scene code built it (three.js conventions: UV v up).
#[derive(Clone, Debug, Default)]
pub struct Geometry {
    pub positions: Vec<f32>,
    pub normals: Vec<f32>,
    pub uvs: Vec<f32>,
    pub indices: Vec<u32>,
    /// (first index, index count, material index) per group: a mesh with several materials (`Kind::Mesh::materials`)
    /// draws each group's triangles with its material; none: one material for all.
    pub groups: Vec<[u32; 3]>,
    /// Vertex colours (three.js's `color` attribute: linear RGB per vertex), or none. A material with `vertexColors`
    /// multiplies its colour by them (F_VCOLOR).
    pub colors: Vec<f32>,
}

/// How stateful particles collide: a plane at `plane` (y, m), the voxel occupancy grid; a bounce keeps `restitution` of
/// the speed along the surface's normal and loses `friction` of it across.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct ParticleCollide {
    pub plane: Option<f32>,
    pub voxels: bool,
    pub restitution: f32,
    pub friction: f32,
}

/// A world-aligned occupancy grid of the voxel engine's objects (a cell occupied if any voxel in it is): one bit a cell,
/// 32 cells along x a word, rows x then z then y; the word ranges changed since it was last uploaded.
#[derive(Clone, Debug, Default)]
pub struct Occupancy {
    pub origin: [f32; 3],
    pub cell: f32,
    pub dims: [u32; 3],
    pub words: Vec<u32>,
    pub dirty: Vec<(usize, usize)>,
}

impl Occupancy {
    /// Words per row (x).
    pub fn row_words(&self) -> usize {
        (self.dims[0] as usize).div_ceil(32)
    }
}

/// A density grid (`DensityGrid` in packages/scene; ROADMAP § 6 step 5b): `dims` cells over a box `VolumeMesh`, four
/// numbers a cell (field A: what the volume function reads with `vgrid`), given by the game (`data`, x fastest, then y,
/// then z; None: zeros) and, with a grid program, changed every frame on the GPU (renderer/shaders/grid_sim.wgsl; a
/// second field B of four numbers is the program's own, e.g. a velocity).
#[derive(Clone, Debug)]
pub struct DensityGrid {
    pub dims: [u32; 3],
    pub data: Option<Arc<Vec<f32>>>,
    /// The grid program (by name) and its 32 parameter floats.
    pub program: Option<(String, Vec<f32>)>,
}

/// A grid's most cells per axis (pathtrace.wgsl `vgrid` packs them in 10 bits each) and in all (8 bytes a cell and
/// field: 67 MB, four times that with a program); a scene's grids together: twice that, at most 2048 layers along z
/// (they are stacked in one 3D texture).
pub const GRID_MAX_AXIS: u32 = 512;
pub const GRID_MAX_CELLS: u64 = 1 << 23;
pub const GRID_MAX_SCENE_CELLS: u64 = 1 << 24;
pub const GRID_MAX_LAYERS: u32 = 2048;
/// Sources a grid takes a frame (grid_sim.wgsl `sources`: three vec4 each).
pub const GRID_MAX_SOURCES: usize = 64;

/// Procedural geometry (`ProceduralGeometry` in packages/scene): object-space AABBs (min xyz, max xyz each) that the
/// geometry function `function` (pathtrace.wgsl `gf_<name>`) intersects, and the game's own data it reads (`i.data`):
/// passed by the scene code, or an asset file the scene build reads (src/procasset.rs).
#[derive(Clone, Debug)]
pub struct ProcGeometry {
    pub function: String,
    pub source: ProcSource,
}

#[derive(Clone, Debug)]
pub enum ProcSource {
    Inline(Arc<crate::procasset::ProcBlob>),
    /// Path relative to the asset root.
    Asset(String),
}

/// AABBs a procedural geometry may have: the hit's primitive index has 23 bits (pathtrace.wgsl `PROC_BIT`).
pub const PROC_MAX_BOXES: usize = (1 << 23) - 1;

#[derive(Clone, Debug)]
pub enum TextureSource {
    /// Path relative to the asset root.
    File(String),
    /// Encoded image (PNG / JPEG) the scene code carries (e.g. an embedded atlas).
    Encoded(Arc<Vec<u8>>),
    /// RGBA8 pixels generated by the scene code.
    Pixels { width: u32, height: u32, rgba: Arc<Vec<u8>> },
}

#[derive(Clone, Debug)]
pub struct Texture {
    pub source: TextureSource,
    pub srgb: bool,
    pub wrap: bool,
    pub repeat: [f32; 2],
    pub offset: [f32; 2],
}

#[derive(Clone, Debug)]
pub enum Kind {
    Group,
    /// `own_blas` (scene code's `dynamicGeometry`): instanced with its own BLAS, so replacing its geometry, creating or
    /// removing it is applied in place (live.rs `edit_geometry`) instead of rebuilding the scene; otherwise its
    /// triangles are flattened into the shared groups.
    /// `materials`: one per geometry group (three.js's material array; empty: `material` for every triangle).
    Mesh { geometry: u32, material: u32, own_blas: bool, materials: Vec<u32> },
    /// glTF asset (path relative to the asset root), optionally only some of its nodes (by name).
    /// `functions`: material functions on its materials, by name prefix (`GLTFModel.functions`).
    Model { uri: String, nodes: Option<Vec<String>>, animation: Option<desc::Animation>, functions: Vec<desc::ModelFunction> },
    Light(desc::Light),
    Camera(desc::Camera),
    /// `count` particles: each a quad that the particle function `emitter` (with `params`, 8 vec4) places every frame
    /// on the GPU, drawn with `material`.
    /// `emitter_area` (m², 0 = none): a particle's nominal area for light sampling (scene.rs, pathtrace.wgsl emit_mis).
    Particles { count: u32, emitter: String, params: Vec<f32>, material: u32, emitter_area: f32 },
    /// Stateful GPU particles (`GpuParticles`; ROADMAP § 6 step 5a): up to `capacity`, emitted and updated on the GPU by
    /// the particle program `program` (with `params`, 8 vec4), `rate` a second from the node and as the game spawns
    /// them (`World::particle_spawns`), collided (`collide`), drawn with `material` as `Particles` are.
    GpuParticles { capacity: u32, program: String, params: Vec<f32>, material: u32, emitter_area: f32, rate: f32, collide: ParticleCollide },
    /// A bounded participating medium (`VolumeMesh`): the unit box / sphere (shape 0 / 1) under the node's transform,
    /// its volume function and 32 parameter floats, majorant (1/m) and HG anisotropy.
    /// `homogeneous`: constant coefficients in the function's first parameters (albedo rgb + extinction, emission
    /// rgb), so the live kernel can use them without the function (pathtrace.wgsl `media_homogeneous`).
    /// `grid`: its density grid (`World::grids`; box volumes), which the volume function reads with `vgrid`.
    Volume { function: String, params: Vec<f32>, shape: u32, majorant: f32, g: f32, homogeneous: bool, grid: Option<u32> },
    /// Procedural geometry (`ProceduralMesh`) under the node's transform, shaded with `materials[k]` for the k its
    /// geometry function returns. Always instanced: a move rewrites its transform, never a rebuild.
    Procedural { geometry: u32, materials: Vec<u32> },
    /// Copies of one geometry (scene code's `InstancedMesh`): triangle geometry `geometry` drawn with `materials[0]`,
    /// or procedural geometry (`procedural`) with `materials` as a `Procedural` has them. `capacity` instances, whose
    /// transforms (relative to the node), colours and per-instance data are its `World::instanced` table; one BLAS for
    /// all, one TLAS instance each, so the table changes in place (live.rs `update_instanced`), never a rebuild.
    Instanced { geometry: u32, procedural: bool, materials: Vec<u32>, capacity: u32 },
}

/// The instances of an `Instanced` object (`World::set_instances`, checked there): the first `count` of its
/// `capacity` are drawn. Matrices are column-major 4 x 4 (three.js `instanceMatrix`), relative to the node; colours
/// (three.js `instanceColor`, linear rgb) multiply the material's base colour; per-instance data replaces the node's
/// `customData`.
#[derive(Clone, Debug, Default)]
pub struct InstanceTable {
    pub count: u32,
    pub matrices: Arc<Vec<f32>>,
    pub colors: Option<Arc<Vec<f32>>>,
    pub custom: Option<Arc<Vec<f32>>>,
}

impl InstanceTable {
    pub fn matrix(&self, i: usize) -> Mat4 {
        self.matrices.get(i * 16..i * 16 + 16).map_or(Mat4::ZERO, Mat4::from_cols_slice)
    }
    pub fn color(&self, i: usize) -> [f32; 3] {
        self.colors.as_ref().and_then(|c| c.get(i * 3..i * 3 + 3)).map_or([1.0; 3], |c| [c[0], c[1], c[2]])
    }
    pub fn custom(&self, i: usize, node: [f32; 4]) -> [f32; 4] {
        self.custom.as_ref().and_then(|c| c.get(i * 4..i * 4 + 4)).map_or(node, |c| [c[0], c[1], c[2], c[3]])
    }
}

#[derive(Clone, Debug)]
pub struct Object {
    /// The scene code's id / name for it (picking reports it, gameplay events use it).
    pub name: String,
    pub parent: Option<u32>,
    pub kind: Kind,
    pub position: Vec3,
    pub rotation: Quat,
    pub scale: Vec3,
    pub visible: bool,
    pub cast_shadow: bool,
    /// UE material "Power": scales everything the object emits (meshes, models, its light).
    pub power: f32,
    /// Per-instance data (UE PerInstanceCustomData): any four numbers scene code gives the object, read by material
    /// functions as `i.custom` (particle functions write one per particle).
    pub custom: [f32; 4],
    /// UE Mobility "Movable": scripts move it (and everything under it) without rebuilding the scene; its triangles
    /// are kept apart (dynamic BLASes) and re-transformed in place. Set by scene code, or by the first move.
    pub movable: bool,
    /// A rigid body drives it (renderer/src/physics.rs): movable, and a mesh among them is placed as an instance of its
    /// own BLAS, so a move is its TLAS transform and no triangle.
    pub driven: bool,
    /// Wind sway (`windSway` in packages/scene): the renderer leans the object about its origin with scene time.
    pub sway: Option<Sway>,
    /// The sway's current rotation (identity without one), applied after the object's own rotation.
    pub sway_rot: Quat,
}

impl Object {
    pub fn local(&self) -> Mat4 {
        Mat4::from_scale_rotation_translation(self.scale, self.sway_rot * self.rotation, self.position)
    }
}

/// Rigid wind sway of a plant (ROADMAP § 5 item 6.5; `windSway` in packages/scene/src/effects.ts, which has the same
/// function as `windAngle`; keep in sync). The object leans downwind about its origin, around the horizontal axis across
/// the wind, by angle(t) = A (0.6 + 0.4 sin(w t + p) + 0.2 sin(2.7 w t + 2 p)) radians: a mean lean of 0.6 A with a
/// sway and a faster flutter on it, A = strength / (1 + stiffness), w = 2 pi frequency sqrt(1 + stiffness) (stiffer
/// plants lean less and sway faster). The phase p is given, or a hash of the object's world position (x, z), so a row
/// of plants does not sway in step.
#[derive(Clone, Copy, Debug, PartialEq, serde::Deserialize)]
pub struct Sway {
    /// Where the wind blows, radians in the ground plane: (cos, sin) in (x, z).
    pub direction: f32,
    pub strength: f32,
    /// Hz.
    pub frequency: f32,
    pub stiffness: f32,
    #[serde(default)]
    pub phase: Option<f32>,
}

impl Sway {
    pub fn angle(&self, t: f32, phase: f32) -> f32 {
        let k = 1.0 + self.stiffness.max(0.0);
        let a = self.strength / k;
        let w = std::f32::consts::TAU * self.frequency * k.sqrt();
        a * (0.6 + 0.4 * (w * t + phase).sin() + 0.2 * (2.7 * w * t + 2.0 * phase).sin())
    }

    /// The lean at scene time t: up turns toward the wind's direction.
    pub fn rotation(&self, t: f32, phase: f32) -> Quat {
        let (s, c) = self.direction.sin_cos();
        Quat::from_axis_angle(Vec3::new(s, 0.0, -c), self.angle(t, phase))
    }
}

/// A sway phase from a world position: the same hash as `windPhase` in packages/scene.
pub fn sway_phase(p: Vec3) -> f32 {
    let h = ((p.x * 12.9898 + p.z * 78.233).sin() * 43758.547).fract().abs();
    std::f32::consts::TAU * h
}

