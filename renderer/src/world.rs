    /// Removes an object and its descendants. Returns their ids (those it had: the bodies that drove them go too).
    pub fn remove(&mut self, id: u32) -> Vec<u32> {
        let mut doomed = vec![id];
        let mut k = 0;
        while k < doomed.len() {
            let p = doomed[k];
            doomed.extend(self.objects.iter().filter(|(_, o)| o.parent == Some(p)).map(|(i, _)| *i));
            k += 1;
        }
        // A lone object with its own BLAS, an instanced mesh or a static model is removed in place (or never added, if it
        // came in this batch; live.rs `edit_geometry` rebuilds for what it cannot take out).
        if let [only] = doomed[..] {
            if self.objects.get(&only).is_some_and(|o| own_blas(&o.kind) || matches!(o.kind, Kind::Instanced { procedural: false, .. } | Kind::Model { animation: None, .. })) {
                self.instanced.remove(&only);
                self.objects.remove(&only);
                if !self.changes.added.remove(&only) {
                    self.changes.removed.insert(only);
                }
                return doomed;
            }
        }
        for &d in &doomed {
            self.instanced.remove(&d);
            if self.objects.remove(&d).is_some() {
                self.changes.structural = true;
            }
        }
        doomed
    }

    pub fn set_environment(&mut self, e: desc::Environment) {
        let sky_same = format!("{:?}", self.environment.sky) == format!("{:?}", e.sky);
        let fog_shape = |f: &Option<desc::Fog>| f.as_ref().map(|f| (f.volumetric.is_some(), f.density > 0.0));
        // (A background appearing or going is a kernel feature, F_BACKGROUND: a rebuild; a new colour is not.)
        if !sky_same || fog_shape(&self.environment.fog) != fog_shape(&e.fog) || self.environment.background.is_some() != e.background.is_some() {
            self.changes.structural = true;
        } else {
            self.changes.environment = true;
        }
        self.environment = e;
    }

