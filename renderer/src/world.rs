    /// Creates or replaces a density grid. New data for a grid of the same size and program is uploaded in place; a
    /// new grid, another size or another program rebuilds the scene.
    pub fn set_grid(&mut self, id: u32, dims: [u32; 3], channels: u32, data: Option<&[f32]>, program: Option<(String, Vec<f32>)>) -> Result<()> {
        let cells = dims.iter().map(|&d| d as u64).product::<u64>();
        if dims.iter().any(|&d| d == 0 || d > GRID_MAX_AXIS) || cells > GRID_MAX_CELLS {
            return Err(anyhow!("density grid {id}: size {dims:?} (1 to {GRID_MAX_AXIS} cells an axis, at most {GRID_MAX_CELLS} in all)"));
        }
        if channels != 1 && channels != 4 {
            return Err(anyhow!("density grid {id}: {channels} channels (1 or 4)"));
        }
        let data = match data {
            Some(d) => {
                if d.len() as u64 != cells * channels as u64 || d.iter().any(|v| !v.is_finite()) {
                    return Err(anyhow!("density grid {id}: data must be {} finite numbers ({channels} a cell)", cells * channels as u64));
                }
                Some(Arc::new(if channels == 4 { d.to_vec() } else { d.iter().flat_map(|&v| [v, 0.0, 0.0, 0.0]).collect() }))
            }
            None => None,
        };
        // The world's grids hold at most twice a scene's cells: over that, the ones no volume names any more go (but
        // this batch's, whose volumes may follow), and if that is not enough the grid is refused.
        let others = |w: &World| w.grids.iter().filter(|(k, _)| **k != id).map(|(_, g)| g.dims.iter().map(|&d| d as u64).product::<u64>()).sum::<u64>();
        if others(self) + cells > 2 * GRID_MAX_SCENE_CELLS {
            let used: HashSet<u32> = self.objects.values().filter_map(|o| if let Kind::Volume { grid: Some(g), .. } = &o.kind { Some(*g) } else { None }).collect();
            let fresh = self.changes.grids_new.clone();
            self.grids.retain(|k, _| used.contains(k) || fresh.contains(k));
            if others(self) + cells > 2 * GRID_MAX_SCENE_CELLS {
                return Err(anyhow!("density grid {id}: the world's density grids exceed {} cells", 2 * GRID_MAX_SCENE_CELLS));
            }
        }
        self.changes.grids_new.insert(id);
        let same = self.grids.get(&id).is_some_and(|g| g.dims == dims && g.program == program);
        if same {
            if data.is_some() {
                self.grid_dirty.insert(id);
            }
        } else {
            self.changes.structural = true;
        }
        // (No data with a same grid: its contents stay, e.g. a simulated grid whose parameters were sent again.)
        let keep = if same && data.is_none() { self.grids.get(&id).and_then(|g| g.data.clone()) } else { None };
        self.grids.insert(id, DensityGrid { dims, data: data.or(keep), program });
        Ok(())
    }

    /// Sources the game gives a volume's grid program (12 floats each), taken by the live view's next frame.
    pub fn add_grid_sources(&mut self, id: u32, data: &[f32]) -> Result<()> {
        if !matches!(self.objects.get(&id).map(|o| &o.kind), Some(Kind::Volume { grid: Some(_), .. })) {
            return Err(anyhow!("grid sources: object {id} is not a volume with a density grid"));
        }
        if data.len() % 12 != 0 || data.iter().any(|v| !v.is_finite()) {
            return Err(anyhow!("grid sources: 12 finite floats a source"));
        }
        let pending = self.grid_sources.entry(id).or_default();
        let room = (GRID_MAX_SOURCES * 12).saturating_sub(pending.len());
        pending.extend_from_slice(&data[..data.len().min(room)]);
        Ok(())
    }

    pub fn set_geometry_fn(&mut self, name: &str, code: String, helpers: String) {
        if self.geometry_fns.get(name).is_some_and(|(c, h)| *c == code && *h == helpers) {
            return;
        }
        self.geometry_fns.insert(name.to_string(), (code, helpers));
        self.changes.structural = true;
    }

    pub fn set_particle_program(&mut self, name: &str, emit: String, update: String, helpers: String) {
        let v = (emit, update, helpers);
        if self.particle_programs.get(name) == Some(&v) {
            return;
        }
        self.particle_programs.insert(name.to_string(), v);
        self.changes.structural = true;
    }

    /// Particles the game spawns into a `GpuParticles` node (8 floats each), taken by the live view's next frame.
    pub fn spawn_particles(&mut self, id: u32, data: &[f32]) -> Result<()> {
        if !matches!(self.objects.get(&id).map(|o| &o.kind), Some(Kind::GpuParticles { .. })) {
            return Err(anyhow!("spawn: object {id} is not a GpuParticles node"));
        }
        if data.len() % 8 != 0 || data.iter().any(|v| !v.is_finite()) {
            return Err(anyhow!("spawn: 8 finite floats a particle"));
        }
        // At most what one frame takes (gpu.rs MAX_SPAWNS) waits per node: the rest is dropped.
        let pending = self.particle_spawns.entry(id).or_default();
        let room = (crate::gpu::MAX_SPAWNS * 8).saturating_sub(pending.len());
        pending.extend_from_slice(&data[..data.len().min(room)]);
        Ok(())
    }

    pub fn set_particle_fn(&mut self, name: &str, code: String, helpers: String) {
        if self.particle_fns.get(name).is_some_and(|(c, h)| *c == code && *h == helpers) {
            return;
        }
        self.particle_fns.insert(name.to_string(), (code, helpers));
        self.changes.structural = true;
    }

    /// Objects drawn: visible themselves and all their ancestors.
    /// Files the scene reads from the asset root: models and file textures (uris, sorted).
    pub fn files(&self) -> Vec<String> {
        let models = self.objects.values().filter_map(|o| match &o.kind {
            Kind::Model { uri, .. } => Some(uri.clone()),
            _ => None,
        });
        let textures = self.textures.values().filter_map(|t| match &t.source {
            TextureSource::File(uri) => Some(uri.clone()),
            TextureSource::Encoded(_) | TextureSource::Pixels { .. } => None,
        });
        let procs = self.proc_geometries.values().filter_map(|g| match &g.source {
            ProcSource::Asset(uri) => Some(uri.clone()),
            ProcSource::Inline(_) => None,
        });
        let set: std::collections::BTreeSet<String> = models.chain(textures).chain(procs).collect();
        set.into_iter().collect()
    }

    pub fn shown(&self, id: u32) -> bool {
        let mut cur = Some(id);
        while let Some(i) = cur {
            match self.objects.get(&i) {
                Some(o) if o.visible => cur = o.parent,
                Some(_) => return false,
                None => return true,
            }
        }
        true
    }
