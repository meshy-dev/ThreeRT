    pub fn world_matrix(&self, id: u32) -> Mat4 {
        let mut m = Mat4::IDENTITY;
        let mut cur = Some(id);
        let mut guard = 0;
        while let Some(i) = cur {
            let Some(o) = self.objects.get(&i) else { break };
            m = o.local() * m;
            cur = o.parent;
            guard += 1;
            if guard > 1024 {
                break;
            }
        }
        m
    }

    /// Ids in an order where parents come before children.
    pub fn ordered(&self) -> Vec<u32> {
        let mut out = Vec::with_capacity(self.objects.len());
        let mut placed: HashSet<u32> = HashSet::new();
        let mut rest: Vec<u32> = self.objects.keys().copied().collect();
        while !rest.is_empty() {
            let before = rest.len();
            rest.retain(|i| {
                let ready = self.objects[i].parent.is_none_or(|p| placed.contains(&p) || !self.objects.contains_key(&p));
                if ready {
                    placed.insert(*i);
                    out.push(*i);
                }
                !ready
            });
            if rest.len() == before {
                out.append(&mut rest);
            }
        }
        out
    }

