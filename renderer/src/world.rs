/// What changed since the last commit.
#[derive(Default, Debug, Clone)]
pub struct Changes {
    pub structural: bool,
    pub materials: HashSet<u32>,
    /// Objects whose light parameters changed.
    pub lights: HashSet<u32>,
    pub powers: HashSet<u32>,
    /// Objects whose per-instance data changed.
    pub customs: HashSet<u32>,
    pub environment: bool,
    pub camera: bool,
    /// The atmosphere's sun moved (time of day): the live view rewrites its light and re-bakes the sky in place.
    pub sun: bool,
    /// Only the camera's manual exposure value changed: applied in place.
    pub exposure: bool,
    /// Models whose animation pose changed.
    pub poses: HashSet<u32>,
    /// Movable objects that moved: everything under them is re-transformed in place.
    pub moved: HashSet<u32>,
    /// Objects made movable by their first move (that move rebuilds once).
    pub promoted: Vec<String>,
    /// Meshes given their own BLAS (`own_blas`) by their geometry's first change, updated or replaced, without scene
    /// code's `dynamicGeometry` (three.js code changes geometry without telling): that change rebuilds once, the next
    /// apply in place. Frame log `fallback: promote`.
    pub promoted_geometry: Vec<String>,
    /// Objects created (or re-created) in this batch: the rebuild builds them where they are, so setting their
    /// transform is not a move.
    pub created: HashSet<u32>,
    /// Geometry edits the live view can apply in place (live.rs `edit_geometry`), when nothing else is structural:
    /// geometries replaced, objects created (or re-created with other geometry or materials) and objects removed,
    /// whose objects carry their own BLAS (procedural meshes, `own_blas` meshes). The live view falls back to a
    /// rebuild for what it cannot apply.
    pub geometries: HashSet<u32>,
    pub added: BTreeSet<u32>,
    pub removed: BTreeSet<u32>,
    /// Instanced objects whose instances changed (table, node transform, power, customData): rewritten in place
    /// (live.rs `update_instanced`).
    pub instanced: HashSet<u32>,
    /// Density grids created in this batch (their volume objects may not exist yet: `World::set_grid` keeps them).
    pub grids_new: BTreeSet<u32>,
    /// Materials created in this batch that bring no texture and no material function: the live view adds them in
    /// place (live.rs `add_materials`; a rebuild for one it cannot take), so an object added while the game runs may
    /// come with a material of its own.
    pub new_materials: BTreeSet<u32>,
}

impl Changes {
    pub fn any(&self) -> bool {
        self.structural || !self.new_materials.is_empty() || !self.materials.is_empty() || !self.lights.is_empty() || !self.powers.is_empty() || !self.customs.is_empty() || self.environment || self.camera || self.sun || self.exposure || !self.poses.is_empty() || !self.moved.is_empty() || !self.instanced.is_empty() || self.edits()
    }
    /// Geometry edits are pending (`geometries`, `added`, `removed`).
    pub fn edits(&self) -> bool {
        !self.geometries.is_empty() || !self.added.is_empty() || !self.removed.is_empty()
    }
}

/// An object kind whose geometry lives in its own BLAS (one TLAS instance per object): its edits apply in place.
pub fn own_blas(k: &Kind) -> bool {
    matches!(k, Kind::Procedural { .. } | Kind::Mesh { own_blas: true, .. })
}

