    /// An instanced object's instances: `count` drawn, `matrices` (16 numbers each), optionally `colors` (3 each) and
    /// per-instance data (4 each), all for its whole capacity; None keeps what it had. Game code is untrusted: sizes
    /// are checked, colours and data made finite (colours >= 0); a matrix that is not finite or not invertible hides
    /// its instance (live.rs, scene.rs). Colours appearing or going rebuild (a kernel feature); the rest is in place.
    pub fn set_instances(&mut self, id: u32, count: u32, matrices: Option<Vec<f32>>, colors: Option<Vec<f32>>, custom: Option<Vec<f32>>) -> Result<()> {
        let o = self.objects.get(&id).ok_or_else(|| anyhow!("unknown object {id}"))?;
        let Kind::Instanced { capacity, .. } = o.kind else { return Err(anyhow!("object {}: not an instanced mesh", o.name)) };
        let cap = capacity as usize;
        if count > capacity {
            return Err(anyhow!("object {}: count {count} exceeds the {capacity} instances", o.name));
        }
        for (what, v, k) in [("matrices", &matrices, 16), ("colors", &colors, 3), ("customData", &custom, 4)] {
            if v.as_ref().is_some_and(|v| v.len() != cap * k) {
                return Err(anyhow!("object {}: {what} must be {k} numbers for each of the {capacity} instances", o.name));
            }
        }
        let t = self.instanced.entry(id).or_default();
        if matrices.is_none() && t.matrices.len() != cap * 16 {
            t.matrices = Arc::new([Mat4::IDENTITY.to_cols_array()].repeat(cap).concat());
        }
        let colored = t.colors.is_some();
        t.count = count;
        if let Some(m) = matrices {
            t.matrices = Arc::new(m);
        }
        if let Some(mut c) = colors {
            for x in &mut c {
                *x = if x.is_finite() { x.max(0.0) } else { 1.0 };
            }
            t.colors = Some(Arc::new(c));
        }
        if let Some(mut c) = custom {
            for x in &mut c {
                if !x.is_finite() {
                    *x = 0.0;
                }
            }
            t.custom = Some(Arc::new(c));
        }
        if t.colors.is_some() != colored {
            self.changes.structural = true;
        } else if !self.changes.created.contains(&id) {
            self.changes.instanced.insert(id);
        }
        Ok(())
    }

